from __future__ import annotations

import sys
from pathlib import Path

import polyfem
from polyfempy.runtime import solve

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_3d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "3D" / "unit-tests" / "5-cubes-fast.json"

model = polyfem.model()

material_1 = polyfem.neo_hookean(E=100000, nu=0.4, rho=1000)

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "cube.msh"),
    transformation=polyfem.transformation(translation=[0, 0, 0], scale=[0.2]),
)
body_1.material(material_1)

body_2 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "cube.msh"),
    transformation=polyfem.transformation(translation=[0, 0.205, 0], scale=[0.2]),
    same_volume_as=body_1,
)
body_2.material(material_1)

body_3 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "cube.msh"),
    transformation=polyfem.transformation(translation=[0, 0.41, 0], scale=[0.2]),
    same_volume_as=body_1,
)
body_3.material(material_1)

body_4 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "cube.msh"),
    transformation=polyfem.transformation(translation=[0, 0.615, 0], scale=[0.2]),
    same_volume_as=body_1,
)
body_4.material(material_1)

body_5 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "cube.msh"),
    transformation=polyfem.transformation(translation=[0, 0.82, 0], scale=[0.2]),
    same_volume_as=body_1,
)
body_5.material(material_1)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "plane.obj"),
    transformation=polyfem.transformation(translation=[0, -0.315, 0], dimensions=[2, 0, 2]),
)

polyfem_config = model.config(
    contact=polyfem.contact(enabled=True, dhat=0.001),
    solver=polyfem.solver(
        linear=polyfem.linear(solver='Eigen::PardisoLDLT'),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(method='RobustArmijo'),
            solver='Newton',
        ),
        advanced=polyfem.solver_advanced(lump_mass_matrix=True),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='sim.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
            ),
            vismesh_rel_area=10000000,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=False,
            save_time_sequence=True,
        ),
        directory='results/3D/unit-tests/5-cubes-fast',
    ),
    time=polyfem.time(polyfem.object3(tend=0.1, time_steps=5)),
    rhs=[0, 9.81, 0],
)


if __name__ == "__main__":
    solve(cfg=polyfem_config)
