#!/usr/bin/env python3
"""Classic 3D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/3D/hex_tet/params.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import polyfem
from polyfempy.runtime import solve

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_3d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "3D" / "hex_tet" / "params.json"

model = polyfem.model()

material_1 = polyfem.neo_hookean(E=100000.0, nu=0.45, rho=1000.0)
material_2 = polyfem.neo_hookean(E=100000.0, nu=0.45, rho=1000.0)

body_1 = model.mesh(
    mesh=str(CONTACT_EXAMPLES_DIR / "3D" / "hex_tet" / "hexcube.msh"),
    transformation=polyfem.transformation(
        rotation=[0.0, 0.0, 0.0],
        scale=[1.0, 1.0, 1.0],
        translation=[0.0, 0.0, 0.0],
    ),
)
body_1.material(material_1)

body_2 = model.mesh(
    mesh=str(CONTACT_EXAMPLES_DIR / "3D" / "hex_tet" / "cube.msh"),
    transformation=polyfem.transformation(
        rotation=[0.0, 0.0, 0.0],
        scale=[1.0, 1.0, 1.0],
        translation=[0.0, 1.3, 0.0],
    ),
)
body_2.material(material_2)

body_1.surface_from_file(str(CONTACT_EXAMPLES_DIR / "3D" / "hex_tet" / "surface_sidesets11.txt")).dirichlet(
    dimension=[True, True, True],
    value=[0, 0, 0],
)

polyfem_config = model.config(
    contact=polyfem.contact(
        enabled=True,
        dhat=0.001,
        epsv=0.001,
        friction_coefficient=0.0,
        use_convergent_formulation=False,
    ),
    solver=polyfem.solver(
        linear=polyfem.linear(solver='Eigen::PardisoLDLT'),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(method='RobustArmijo'),
            solver='Newton',
        ),
        advanced=polyfem.solver_advanced(lump_mass_matrix=True),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='sim.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
            ),
            vismesh_rel_area=10000000,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=False,
            save_time_sequence=True,
        ),
        directory='results/3D/hex_tet/params',
    ),
    time=polyfem.time(polyfem.object1(dt=0.025, integrator='ImplicitEuler', tend=5.0)),
    rhs=[0, 9.8, 0],
)


if __name__ == "__main__":
    solve(cfg=polyfem_config)
