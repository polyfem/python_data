#!/usr/bin/env python3
"""Classic 3D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/3D/higher-order/ball-bounce/P3.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import polyfem
from polyfempy.runtime import solve

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_3d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "3D" / "higher-order" / "ball-bounce" / "P3.json"

model = polyfem.model()

material_1 = polyfem.neo_hookean(E=591000, nu=0.45, rho=700)

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "sphere" / "coarse" / "P3.msh"),
    transformation=polyfem.transformation(scale=[0.11938]),
)
body_1.material(material_1)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "plane.obj"),
    transformation=polyfem.transformation(dimensions=[1, 0, 1], translation=[0, -0.2, 0]),
)

polyfem_config = model.config(
    contact=polyfem.contact(
        enabled=True,
        dhat=0.001,
        collision_mesh=polyfem.collision_mesh(
            polyfem.collision_mesh_object2(
                max_edge_length=0.01,
                tessellation_type='irregular',
            ),
        ),
        friction_coefficient=0.2,
    ),
    solver=polyfem.solver(
        linear=polyfem.linear(solver='Eigen::PardisoLDLT'),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(method='RobustArmijo'),
            solver='Newton',
        ),
        advanced=polyfem.solver_advanced(lump_mass_matrix=False),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='sim.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
                contact_forces=True,
            ),
            vismesh_rel_area=10000000,
            high_order_mesh=True,
            skip_frame=10,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=False,
            save_time_sequence=True,
        ),
        directory='results/3D/higher-order/ball-bounce/P3',
    ),
    space=polyfem.space(discr_order=3),
    time=polyfem.time(polyfem.object1(dt=0.001, integrator='BDF2', tend=1)),
    rhs=[0, 9.81, 0],
)


if __name__ == "__main__":
    solve(cfg=polyfem_config)
