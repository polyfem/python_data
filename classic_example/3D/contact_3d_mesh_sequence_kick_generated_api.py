#!/usr/bin/env python3
"""Classic 3D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/3D/mesh-sequence/kick.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import polyfem
from polyfempy.runtime import solve

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_3d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "3D" / "mesh-sequence" / "kick.json"

model = polyfem.model()

model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "cube.msh"),
    transformation=polyfem.transformation(scale=[0.15], translation=[0.9, 1.25, 1.8]),
)

model.mesh_sequence(
    fps=24,
    is_obstacle=True,
    mesh_sequence='../../../meshes/3D/obstacles/kick-sequence/',
)

model.contact(enabled=True, dhat=0.001)
model.solver(
    linear=polyfem.linear(solver='Eigen::PardisoLDLT'),
    nonlinear=polyfem.nonlinear(
        iterations_per_strategy=1,
        line_search=polyfem.line_search(method='RobustArmijo'),
        solver='Newton',
    ),
    advanced=polyfem.solver_advanced(lump_mass_matrix=True),
)
model.output(
    json='sim.json',
    paraview=polyfem.output_paraview(
        file_name='sim.pvd',
        options=polyfem.options(
            material=True,
            body_ids=True,
            tensor_values=False,
            discretization_order=False,
            nodes=False,
        ),
        vismesh_rel_area=10000000,
    ),
    advanced=polyfem.output_advanced(save_solve_sequence_debug=False, save_time_sequence=True),
    directory='results/3D/mesh-sequence/kick',
)
model.materials(
    items=[
        polyfem.neo_hookean(E=20000.0, nu=0.4, rho=1000),
    ],
)
model.time(dt=0.02, tend=5)
model.rhs([0, 0, 0])

polyfem_config = model.config()


if __name__ == "__main__":
    solve(cfg=polyfem_config)
