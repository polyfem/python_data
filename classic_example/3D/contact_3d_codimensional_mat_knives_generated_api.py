#!/usr/bin/env python3
"""Classic 3D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/3D/codimensional/mat-knives.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import polyfem

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_3d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
    config_for_workspace_from,
    run_solve,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "3D" / "codimensional" / "mat-knives.json"

model = polyfem.model()

material_1 = polyfem.neo_hookean(
    E=20000,
    nu=0.4,
    rho=1000,
)

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "mat" / "mat40x40.msh"),
    transformation=polyfem.transformation(
        translation=[0.5, 1, 0.1],
        rotation=[0, 0, 0.05],
        scale=[1.2],
    ),
    volume_selection=1,
)
body_1.material(material_1)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "triangle.obj"),
    transformation=polyfem.transformation(
        translation=[0.2, -0.1, -0.7],
        rotation=[0, 0, 90],
    ),
    surface_selection=0,
)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "triangle.obj"),
    transformation=polyfem.transformation(
        translation=[0.4, -0.1, -0.7],
        rotation=[0, 0, 90],
    ),
    surface_selection=0,
)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "triangle.obj"),
    transformation=polyfem.transformation(
        translation=[0.6, -0.1, -0.7],
        rotation=[0, 0, 90],
    ),
    surface_selection=0,
)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "triangle.obj"),
    transformation=polyfem.transformation(
        translation=[0.8, -0.1, -0.7],
        rotation=[0, 0, 90],
    ),
    surface_selection=0,
)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "triangle.obj"),
    transformation=polyfem.transformation(
        translation=[0.1, -0.1, 0.3],
        rotation=[0, 180, 90],
        rotation_mode='zyx',
    ),
    surface_selection=0,
)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "triangle.obj"),
    transformation=polyfem.transformation(
        translation=[0.3, -0.1, 0.3],
        rotation=[0, 180, 90],
        rotation_mode='zyx',
    ),
    surface_selection=0,
)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "triangle.obj"),
    transformation=polyfem.transformation(
        translation=[0.5, -0.1, 0.3],
        rotation=[0, 180, 90],
        rotation_mode='zyx',
    ),
    surface_selection=0,
)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "triangle.obj"),
    transformation=polyfem.transformation(
        translation=[0.7, -0.1, 0.3],
        rotation=[0, 180, 90],
        rotation_mode='zyx',
    ),
    surface_selection=0,
)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "triangle.obj"),
    transformation=polyfem.transformation(
        translation=[0.9, -0.1, 0.3],
        rotation=[0, 180, 90],
        rotation_mode='zyx',
    ),
    surface_selection=0,
)

polyfem_config = model.config(
    contact=polyfem.contact(
        enabled=True,
        dhat=0.001,
    ),
    solver=polyfem.solver(
        linear=polyfem.linear(
            solver='Eigen::PardisoLDLT',
        ),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(
                method='RobustArmijo',
            ),
            solver='Newton',
        ),
        advanced=polyfem.solver_advanced(
            lump_mass_matrix=True,
        ),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='mat-knives.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
            ),
            vismesh_rel_area=10000000,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=False,
            save_time_sequence=True,
        ),
    ),
    time=polyfem.time(
        polyfem.object1(
            tend=6,
            dt=0.04,
        ),
    ),
    rhs=[0, 9.81, 0],
)


def config_for_workspace(workspace: Path) -> Any:
    return config_for_workspace_from(polyfem_config, workspace)


def main() -> int:
    return run_solve(polyfem_config, "contact_3d_codimensional_mat_knives_generated_api")


if __name__ == "__main__":
    raise SystemExit(main())
