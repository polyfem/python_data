#!/usr/bin/env python3
"""Classic 3D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/3D/higher-order/golf-ball-P2.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import polyfem

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_3d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
    config_for_workspace_from,
    run_solve,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "3D" / "higher-order" / "golf-ball-P2.json"

model = polyfem.model()

material_1 = polyfem.neo_hookean(
    E=10000000.0,
    nu=0.45,
    rho=1150,
)
material_2 = polyfem.neo_hookean(
    E=200000000000.0,
    nu=0.3,
    rho=7750,
)

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "sphere" / "sphere1K.msh"),
    transformation=polyfem.transformation(
        scale=[0.04],
    ),
    volume_selection=1,
    n_refs=0,
)
body_1.material(material_1)

body_2 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "cube.msh"),
    transformation=polyfem.transformation(
        translation=[0.105, 0, 0],
        dimensions=[0.01, 0.4, 0.4],
    ),
    volume_selection=2,
    n_refs=0,
)
body_2.material(material_2)
body_2_surface_1 = body_2.surface_all(
    id=1,
)

body_1.velocity(
    polyfem.velocity_item(
        value=[67, 0, 0],
    ),
)

body_2.discr_order(
    order=2,
)

body_2_surface_1.dirichlet(
    value=[0, 0, 0],
)

polyfem_config = model.config(
    contact=polyfem.contact(
        enabled=True,
        dhat=6.92820323e-05,
    ),
    solver=polyfem.solver(
        linear=polyfem.linear(
            solver='Eigen::PardisoLDLT',
        ),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(
                method='RobustArmijo',
            ),
            solver='Newton',
        ),
        advanced=polyfem.solver_advanced(
            lump_mass_matrix=True,
        ),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='sim.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
                velocity=True,
            ),
            vismesh_rel_area=10000000,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=False,
            save_time_sequence=True,
        ),
    ),
    time=polyfem.time(
        polyfem.object1(
            tend=0.004,
            dt=2e-05,
        ),
    ),
    rhs=[0, 0, 0],
)


def config_for_workspace(workspace: Path) -> Any:
    return config_for_workspace_from(polyfem_config, workspace)


def main() -> int:
    return run_solve(polyfem_config, "contact_3d_higher_order_golf_ball_p2_generated_api")


if __name__ == "__main__":
    raise SystemExit(main())
