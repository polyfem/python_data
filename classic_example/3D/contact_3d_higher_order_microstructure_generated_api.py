#!/usr/bin/env python3
"""Classic 3D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/3D/higher-order/microstructure.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_3d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
    config_for_workspace_from,
    polyfem,
    run_solve,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "3D" / "higher-order" / "microstructure.json"

model = polyfem.model()

material_1 = polyfem.neo_hookean(
    E=6000000.0,
    nu=0.48,
    rho=1.03,
)

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "microstructure" / "P4.msh"),
    transformation=polyfem.transformation(
        scale=[6.0],
    ),
    volume_selection=1,
)
body_1.material(material_1)

body_2_surface_1000 = model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "cube.msh"),
    transformation=polyfem.transformation(
        translation=[3, 6.12, 3],
        dimensions=[9, 0.2, 9],
    ),
    surface_selection=1000,
)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "cube.msh"),
    transformation=polyfem.transformation(
        translation=[3, -0.12, 3],
        dimensions=[9, 0.2, 9],
    ),
)

body_2_surface_1000.obstacle_displacement(
    value=[0, '4.5 * smooth_abs(t - 1, 5) - 4.5', 0],
)

polyfem_config = model.config(
    contact=polyfem.contact(
        enabled=True,
        dhat=0.001,
        friction_coefficient=0.3,
        collision_mesh=polyfem.collision_mesh(
            polyfem.collision_mesh_object2(
                max_edge_length=0.1,
                tessellation_type='irregular',
            ),
        ),
    ),
    solver=polyfem.solver(
        linear=polyfem.linear(
            solver='Eigen::PardisoLDLT',
        ),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(
                method='RobustArmijo',
            ),
            solver='Newton',
        ),
        advanced=polyfem.solver_advanced(
            lump_mass_matrix=False,
        ),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='sim.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
                contact_forces=True,
            ),
            vismesh_rel_area=10000000,
            high_order_mesh=True,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=False,
            save_time_sequence=True,
        ),
    ),
    space=polyfem.space(
        discr_order=2,
    ),
    time=polyfem.time(
        polyfem.object1(
            tend=2,
            dt=0.01,
        ),
    ),
    rhs=[0, 9800, 0],
)


def config_for_workspace(workspace: Path) -> Any:
    return config_for_workspace_from(polyfem_config, workspace)


def main() -> int:
    return run_solve(polyfem_config, "contact_3d_higher_order_microstructure_generated_api")


if __name__ == "__main__":
    raise SystemExit(main())
