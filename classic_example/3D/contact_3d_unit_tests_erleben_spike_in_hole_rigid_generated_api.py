#!/usr/bin/env python3
"""Classic 3D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/3D/unit-tests/erleben/spike-in-hole-rigid.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import polyfem

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_3d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
    config_for_workspace_from,
    run_solve,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "3D" / "unit-tests" / "erleben" / "spike-in-hole-rigid.json"

model = polyfem.model()

material_1 = polyfem.neo_hookean(E=1000000.0, nu=0.4, rho=1000)

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "erleben" / "spike.msh"),
    transformation=polyfem.transformation(rotation=[0, 0, 180], translation=[0, 2.0001, 0]),
    volume_selection=1,
)
body_1.material(material_1)
body_1_surface_11 = body_1.surface_axis(axis=2, id=11, position=2)
body_1_point_1 = body_1.point_box(box=[[0.1, 2, -10], [1, 10, 10]], id=1)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "erleben" / "hole.obj"),
    transformation=polyfem.transformation(translation=[0, -1, 0]),
    surface_selection=0,
)

body_1_point_1.dirichlet(value=['t', 0, 0])

polyfem_config = model.config(
    contact=polyfem.contact(enabled=True, dhat=0.001),
    solver=polyfem.solver(
        linear=polyfem.linear(solver='Eigen::PardisoLDLT'),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(method='RobustArmijo'),
            solver='Newton',
        ),
        advanced=polyfem.solver_advanced(lump_mass_matrix=True),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='spike-in-hole.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
            ),
            vismesh_rel_area=10000000,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=False,
            save_time_sequence=True,
        ),
    ),
    time=polyfem.time(polyfem.object1(dt=0.025, tend=5)),
    rhs=[0, 9.81, 0],
)


def config_for_workspace(workspace: Path) -> Any:
    return config_for_workspace_from(polyfem_config, workspace)


def main() -> int:
    return run_solve(polyfem_config, "contact_3d_unit_tests_erleben_spike_in_hole_rigid_generated_api")


if __name__ == "__main__":
    raise SystemExit(main())
