#!/usr/bin/env python3
"""Classic 3D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/3D/stress-tests/spheres_collide-P3.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import polyfem

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_3d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
    config_for_workspace_from,
    run_solve,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "3D" / "stress-tests" / "spheres_collide-P3.json"

model = polyfem.model()

material_1 = polyfem.material_sum(
    models=polyfem.material_models(
        items=[
            {
                'type': 'NeoHookean',
                'E': 10000.0,
                'nu': 0.45,
            },
            polyfem.models_inversion_barrier(E=10000.0, nu=0.45),
        ],
    ),
    rho=1000,
)
material_2 = polyfem.material_sum(
    models=polyfem.material_models(
        items=[
            {
                'type': 'NeoHookean',
                'E': 10000000.0,
                'nu': 0.3,
            },
            polyfem.models_inversion_barrier(E=100000000.0, nu=0.3),
        ],
    ),
    rho=8000,
)

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "sphere" / "coarse" / "icosphere.msh"),
    transformation=polyfem.transformation(scale=[1.0], translation=[0, 0, 0]),
    volume_selection=1,
)
body_1.material(material_1)

body_2 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "sphere" / "coarse" / "icosphere.msh"),
    transformation=polyfem.transformation(scale=[0.3], translation=[-1.6, 0, 0]),
    volume_selection=2,
)
body_2.material(material_2)

body_2.velocity(polyfem.velocity_item(value=[10, 0, 0]))

polyfem_config = model.config(
    contact=polyfem.contact(enabled=True, dhat=0.001),
    solver=polyfem.solver(
        linear=polyfem.linear(solver='Eigen::PardisoLDLT'),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(method='RobustArmijo'),
            solver='Newton',
        ),
        advanced=polyfem.solver_advanced(lump_mass_matrix=False, check_inversion='Conservative'),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='sim.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
            ),
            vismesh_rel_area=10000000,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=False,
            save_time_sequence=True,
        ),
    ),
    time=polyfem.time(polyfem.object1(tend=1, dt=0.01)),
    space=polyfem.space(discr_order=3),
    rhs=[0, 0, 0],
)


def config_for_workspace(workspace: Path) -> Any:
    return config_for_workspace_from(polyfem_config, workspace)


def main() -> int:
    return run_solve(polyfem_config, "contact_3d_stress_tests_spheres_collide_p3_generated_api")


if __name__ == "__main__":
    raise SystemExit(main())
