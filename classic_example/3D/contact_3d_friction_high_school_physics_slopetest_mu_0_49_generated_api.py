#!/usr/bin/env python3
"""Classic 3D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/3D/friction/high-school-physics-slopetest-mu=0.49.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import polyfem

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_3d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
    config_for_workspace_from,
    run_solve,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "3D" / "friction" / "high-school-physics-slopetest-mu=0.49.json"

model = polyfem.model()

material_1 = polyfem.neo_hookean(E=1000000000.0, nu=0.4, rho=1000)
material_2 = polyfem.neo_hookean(E=200000000000.0, nu=0.3, rho=7750)

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "cube.msh"),
    transformation=polyfem.transformation(rotation=[0, 0, -26.565], scale=[1.0], translation=[0, 0, 0]),
    volume_selection=1,
)
body_1.material(material_1)

body_2 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "simple" / "cube.msh"),
    transformation=polyfem.transformation(
        dimensions=[10, 0.01, 10],
        rotation=[0, 0, -26.565],
        translation=[2, -1.566, 0],
    ),
    volume_selection=2,
)
body_2.material(material_2)
body_2_surface_1 = body_2.surface_all(id=1)

body_2_surface_1.dirichlet(value=[0, 0, 0])

polyfem_config = model.config(
    contact=polyfem.contact(enabled=True, dhat=0.001, epsv=1e-05, friction_coefficient=0.49),
    solver=polyfem.solver(
        linear=polyfem.linear(solver='Eigen::PardisoLDLT'),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(method='RobustArmijo'),
            solver='Newton',
        ),
        advanced=polyfem.solver_advanced(lump_mass_matrix=True),
        contact=polyfem.solver_contact(friction_convergence_tol=0.01, friction_iterations=-1),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='sim.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
                contact_forces=True,
                friction_forces=True,
            ),
            vismesh_rel_area=10000000,
            surface=True,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=False,
            save_time_sequence=True,
        ),
    ),
    time=polyfem.time(polyfem.object1(dt=0.025, tend=2.5)),
    rhs=[0, 9.81, 0],
)


def config_for_workspace(workspace: Path) -> Any:
    return config_for_workspace_from(polyfem_config, workspace)


def main() -> int:
    return run_solve(polyfem_config, "contact_3d_friction_high_school_physics_slopetest_mu_0_49_generated_api")


if __name__ == "__main__":
    raise SystemExit(main())
