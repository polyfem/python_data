#!/usr/bin/env python3
"""Classic 3D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/3D/stress-tests/dolphin-funnel-Linf.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_3d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
    config_for_workspace_from,
    polyfem,
    run_solve,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "3D" / "stress-tests" / "dolphin-funnel-Linf.json"

model = polyfem.model()

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "3D" / "creatures" / "dolphin.msh"),
    transformation=polyfem.transformation(
        rotation=[0, 0, 40],
        scale=[0.008394050297],
        translation=[0.4547526249, 0.5227239301, -0.02286748313],
    ),
    volume_selection=1,
)
body_1_surface_1 = body_1.surface_box(
    box=[[0.97, 0, 0], [1, 1, 1]],
    id=1,
    relative=True,
)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "3D" / "obstacles" / "funnel.obj"),
    transformation=polyfem.transformation(
        rotation=[0, 0, 90],
        scale=[1.5],
        translation=[1.76, 0.86, 0.42],
    ),
    surface_selection=0,
)

body_1_surface_1.dirichlet(
    dimension=[True, False, False],
    value=['min(0.5*t, 10)', 0, 0],
)

polyfem_config = model.config(
    contact=polyfem.contact(
        enabled=True,
        dhat=0.001,
    ),
    solver=polyfem.solver(
        linear=polyfem.linear(
            solver='Eigen::PardisoLDLT',
        ),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(
                method='RobustArmijo',
            ),
            solver='Newton',
            max_iterations=10000,
            norm_type='Linf',
        ),
        advanced=polyfem.solver_advanced(
            lump_mass_matrix=True,
        ),
        augmented_lagrangian=polyfem.augmented_lagrangian(
            nonlinear=polyfem.augmented_lagrangian_nonlinear(
                max_iterations=100,
                allow_out_of_iterations=True,
            ),
        ),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='dolphin-funnel.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
            ),
            vismesh_rel_area=10000000,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=False,
            save_time_sequence=True,
        ),
    ),
    materials=polyfem.materials(
        items=[
            polyfem.neo_hookean(
                E=10000,
                nu=0.4,
                rho=1000,
            ),
        ],
    ),
    time=polyfem.time(
        polyfem.object1(
            dt=0.04,
            tend=32,
        ),
    ),
    rhs=[0, 0, 0],
)


def config_for_workspace(workspace: Path) -> Any:
    return config_for_workspace_from(polyfem_config, workspace)


def main() -> int:
    return run_solve(polyfem_config, "contact_3d_stress_tests_dolphin_funnel_linf_generated_api")


if __name__ == "__main__":
    raise SystemExit(main())
