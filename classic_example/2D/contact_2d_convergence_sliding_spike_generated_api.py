#!/usr/bin/env python3
"""Classic 2D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/2D/convergence/sliding-spike.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_2d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
    config_for_workspace_from,
    polyfem,
    run_solve,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "2D" / "convergence" / "sliding-spike.json"

model = polyfem.model()

material_1 = polyfem.neo_hookean(
    E=100000.0,
    nu=0.3,
    rho=7750,
)

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "2D" / "simple" / "erleben" / "spike.obj"),
    transformation=polyfem.transformation(
        rotation=[180.0],
        translation=[-5, 2.0001],
    ),
    volume_selection=1,
)
body_1.material(material_1)
body_1_surface_1 = body_1.surface_axis(
    axis=2,
    id=1,
    position=2,
)

model.obstacle_mesh(
    mesh=str(MESHES_DIR / "2D" / "obstacles" / "line.obj"),
    n_refs=6,
    transformation=polyfem.transformation(
        translation=[0, -1],
    ),
    surface_selection=0,
)

body_1_surface_1.dirichlet(
    value=['10*t', 0],
)

polyfem_config = model.config(
    contact=polyfem.contact(
        enabled=True,
        dhat=0.001,
        use_convergent_formulation=True,
    ),
    solver=polyfem.solver(
        linear=polyfem.linear(
            solver='Eigen::PardisoLDLT',
        ),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(
                method='RobustArmijo',
            ),
            solver='Newton',
        ),
        advanced=polyfem.solver_advanced(
            lump_mass_matrix=True,
        ),
        contact=polyfem.solver_contact(
            barrier_stiffness=10000.0,
        ),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='sliding-spike.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
            ),
            vismesh_rel_area=10000000,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=False,
            save_time_sequence=True,
        ),
    ),
    time=polyfem.time(
        polyfem.object3(
            time_steps=400,
            tend=1,
            quasistatic=True,
        ),
    ),
    rhs=[0, 9.81],
)


def config_for_workspace(workspace: Path) -> Any:
    return config_for_workspace_from(polyfem_config, workspace)


def main() -> int:
    return run_solve(polyfem_config, "contact_2d_convergence_sliding_spike_generated_api")


if __name__ == "__main__":
    raise SystemExit(main())
