#!/usr/bin/env python3
"""Classic 2D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/2D/static/friction-slope.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import polyfem

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_2d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
    config_for_workspace_from,
    run_solve,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "2D" / "static" / "friction-slope.json"

model = polyfem.model()

body_1 = model.geometry_mesh(
    mesh=str(MESHES_DIR / "2D" / "simple" / "square.obj"),
    transformation=polyfem.transformation(translation=[0, 0], rotation=[-30.0], scale=[5, 0.02]),
)
body_1_surface_1 = body_1.surface_all(id=1)

model.geometry_mesh(
    mesh=str(MESHES_DIR / "2D" / "simple" / "square1K.msh"),
    transformation=polyfem.transformation(translation=[0.26, 0.4503], rotation=[-30.0], scale=[1.0]),
)

body_1_surface_1.dirichlet(value=[0, 0])

polyfem_config = model.config(
    contact=polyfem.contact(enabled=True, dhat=0.001, friction_coefficient=0.6),
    solver=polyfem.solver(
        linear=polyfem.linear(solver='Eigen::PardisoLDLT'),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(method='RobustArmijo'),
            solver='Newton',
            max_iterations=300,
            norm_type='Euclidean',
            rel_grad_norm_tol=0,
            first_grad_norm_tol=1e-10,
            grad_norm_tol=1e-05,
            x_delta_tol=1e-12,
            advanced=polyfem.nonlinear_advanced(f_delta_tol=1e-05),
        ),
        advanced=polyfem.solver_advanced(
            lump_mass_matrix=True,
            lagged_regularization_weight=10,
            lagged_regularization_iterations=1,
        ),
        contact=polyfem.solver_contact(
            friction_iterations=-1,
            friction_convergence_tol=0.01,
            barrier_stiffness=1000000000.0,
        ),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='sol.vtu',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
            ),
            vismesh_rel_area=10000000,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=True,
            save_time_sequence=False,
            save_nl_solve_sequence=False,
        ),
    ),
    materials=polyfem.materials(
        items=[
            polyfem.neo_hookean(E=70000000.0, nu=0.48, rho=1240),
        ],
    ),
    rhs=[0, 9.81],
)


def config_for_workspace(workspace: Path) -> Any:
    return config_for_workspace_from(polyfem_config, workspace)


def main() -> int:
    return run_solve(polyfem_config, "contact_2d_static_friction_slope_generated_api")


if __name__ == "__main__":
    raise SystemExit(main())
