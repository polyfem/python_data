#!/usr/bin/env python3
"""Classic 2D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/2D/friction/moving-ground.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import polyfem

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_2d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
    config_for_workspace_from,
    run_solve,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "2D" / "friction" / "moving-ground.json"

model = polyfem.model()

material_1 = polyfem.neo_hookean(E=200000000000.0, nu=0.3, rho=7750)
material_2 = polyfem.neo_hookean(E=200000000000.0, nu=0.3, rho=7750)

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "2D" / "simple" / "square.obj"),
    enabled=True,
    transformation=polyfem.transformation(translation=[0, 0.5075]),
    volume_selection=1,
)
body_1.material(material_1)

body_2 = model.mesh(
    mesh=str(MESHES_DIR / "2D" / "simple" / "square.obj"),
    enabled=True,
    transformation=polyfem.transformation(translation=[0, 0], scale=[4, 0.01]),
    volume_selection=2,
)
body_2.material(material_2)
body_2_surface_1 = body_2.surface_all(id=1)

body_1.velocity(polyfem.velocity_item(value=[0, 0]))

body_2_surface_1.dirichlet(value=['4 * t^2', 0])

polyfem_config = model.config(
    contact=polyfem.contact(enabled=True, dhat=0.001, epsv=0.004, friction_coefficient=0.5),
    solver=polyfem.solver(
        linear=polyfem.linear(solver='Eigen::PardisoLDLT'),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(method='RobustArmijo'),
            solver='Newton',
        ),
        advanced=polyfem.solver_advanced(lump_mass_matrix=True),
        contact=polyfem.solver_contact(friction_iterations=10),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='sim.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
                contact_forces=True,
            ),
            vismesh_rel_area=10000000,
        ),
        advanced=polyfem.output_advanced(save_solve_sequence_debug=True, save_time_sequence=True),
    ),
    time=polyfem.time(polyfem.object1(tend=1, dt=0.01)),
    rhs=[0, 9.81],
)


def config_for_workspace(workspace: Path) -> Any:
    return config_for_workspace_from(polyfem_config, workspace)


def main() -> int:
    return run_solve(polyfem_config, "contact_2d_friction_moving_ground_generated_api")


if __name__ == "__main__":
    raise SystemExit(main())
