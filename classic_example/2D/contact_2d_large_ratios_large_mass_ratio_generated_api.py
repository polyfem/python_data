#!/usr/bin/env python3
"""Classic 2D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/2D/large-ratios/large-mass-ratio.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import polyfem
from polyfempy.runtime import solve

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_2d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "2D" / "large-ratios" / "large-mass-ratio.json"

model = polyfem.model()

material_1 = polyfem.neo_hookean(E=100000000, nu=0.4, rho=10000)
material_2 = polyfem.neo_hookean(E=1000000, nu=0.4, rho=1000)
material_3 = polyfem.neo_hookean(E=200000000000, nu=0.3, rho=7750)

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "2D" / "simple" / "square.obj"),
    transformation=polyfem.transformation(scale=[1.0], translation=[0, 0.45]),
)
body_1.material(material_1)

body_2 = model.mesh(
    mesh=str(MESHES_DIR / "2D" / "simple" / "square.obj"),
    transformation=polyfem.transformation(scale=[0.1], translation=[0, -0.15]),
)
body_2.material(material_2)

body_3 = model.mesh(
    mesh=str(MESHES_DIR / "2D" / "simple" / "square.obj"),
    transformation=polyfem.transformation(scale=[2, 0.01], translation=[0, -0.25]),
)
body_3.material(material_3)
body_3_surface = body_3.surface_all()

body_3_surface.dirichlet(value=[0, 0])

polyfem_config = model.config(
    contact=polyfem.contact(enabled=True, dhat=0.001, friction_coefficient=0.1),
    solver=polyfem.solver(
        linear=polyfem.linear(solver='Eigen::PardisoLDLT'),
        nonlinear=polyfem.nonlinear(
            iterations_per_strategy=1,
            line_search=polyfem.line_search(method='RobustArmijo'),
            solver='Newton',
        ),
        advanced=polyfem.solver_advanced(lump_mass_matrix=True),
    ),
    output=polyfem.output(
        json='sim.json',
        paraview=polyfem.output_paraview(
            file_name='sim.pvd',
            options=polyfem.options(
                material=True,
                body_ids=True,
                tensor_values=False,
                discretization_order=False,
                nodes=False,
            ),
            vismesh_rel_area=10000000,
        ),
        advanced=polyfem.output_advanced(
            save_solve_sequence_debug=False,
            save_time_sequence=True,
        ),
        directory='results/2D/large-ratios/large-mass-ratio',
    ),
    time=polyfem.time(polyfem.object3(tend=3, time_steps=120)),
    rhs=[0, 9.81],
)


if __name__ == "__main__":
    solve(cfg=polyfem_config)
