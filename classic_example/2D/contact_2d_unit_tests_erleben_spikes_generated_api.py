#!/usr/bin/env python3
"""Classic 2D contact example using generated_api.

Mirrors ``polyfem-data/contact/examples/2D/unit-tests/erleben/spikes.json``.
Generated by tools/generate_classic_contact_examples.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import polyfem
from polyfempy.runtime import solve

EXAMPLE_DIR = Path(__file__).resolve().parent
if str(EXAMPLE_DIR) not in sys.path:
    sys.path.insert(0, str(EXAMPLE_DIR))

from _contact_2d_common import (  # noqa: E402
    CONTACT_EXAMPLES_DIR,
    MESHES_DIR,
)


SOURCE_JSON = CONTACT_EXAMPLES_DIR / "2D" / "unit-tests" / "erleben" / "spikes.json"

model = polyfem.model()

material_1 = polyfem.neo_hookean(E=1000000.0, nu=0.4, rho=1000)

body_1 = model.mesh(
    mesh=str(MESHES_DIR / "2D" / "simple" / "erleben" / "spike.obj"),
    transformation=polyfem.transformation(rotation=[180.0], translation=[0, 3.0001]),
)
body_1.material(material_1)
body_1.rhs(value=[0, 9.81])

model.mesh(
    is_obstacle=True,
    mesh=str(MESHES_DIR / "2D" / "simple" / "erleben" / "spike.obj"),
    transformation=polyfem.transformation(translation=[0, -3]),
)

model.contact(enabled=True, dhat=0.001)
model.solver(
    linear=polyfem.linear(solver='Eigen::PardisoLDLT'),
    nonlinear=polyfem.nonlinear(
        iterations_per_strategy=1,
        line_search=polyfem.line_search(method='RobustArmijo'),
        solver='Newton',
    ),
    advanced=polyfem.solver_advanced(lump_mass_matrix=True),
)
model.output(
    json='sim.json',
    paraview=polyfem.output_paraview(
        file_name='spikes.pvd',
        options=polyfem.options(
            material=True,
            body_ids=True,
            tensor_values=False,
            discretization_order=False,
            nodes=False,
        ),
        vismesh_rel_area=10000000,
    ),
    advanced=polyfem.output_advanced(save_solve_sequence_debug=False, save_time_sequence=True),
    directory='results/2D/unit-tests/erleben/spikes',
)
model.time(dt=0.025, tend=1.25)

polyfem_config = model.config()


if __name__ == "__main__":
    solve(cfg=polyfem_config)
